"""Copy repo ``data/`` into ``backend/data`` and embed it as a Python module.

Vercel's Python runtime traces imports, so a data directory can be left out of
the function bundle even when it is tracked in git. ``app/data_bundle.py`` is a
plain module the tracer always follows; ``app.core.paths`` materializes it when
no on-disk catalog is found.
"""

from __future__ import annotations

import shutil
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
REPO_DATA = BACKEND_ROOT.parent / "data"
BUNDLE_DATA = BACKEND_ROOT / "data"
EMBEDDED = BACKEND_ROOT / "app" / "data_bundle.py"

HEADER = '''"""Generated by scripts/bundle_data.py. Do not edit by hand."""

from __future__ import annotations

DATA: dict[str, str] = {
'''


def main() -> None:
    if not REPO_DATA.is_dir():
        raise SystemExit(f"missing catalog directory: {REPO_DATA}")
    shutil.copytree(REPO_DATA, BUNDLE_DATA, dirs_exist_ok=True)
    EMBEDDED.write_text(_render(REPO_DATA), encoding="utf-8")


def _render(root: Path) -> str:
    lines = [HEADER]
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        relative = path.relative_to(root).as_posix()
        lines.append(f"    {relative!r}: {path.read_text(encoding='utf-8')!r},\n")
    lines.append("}\n")
    return "".join(lines)


if __name__ == "__main__":
    main()
